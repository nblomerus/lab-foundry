"""
Frozen trust-gate gold set — the spec for `library.trust.classify_trust`.

`classify_trust` is a PURE function over a pre-resolved `DocMeta` (no DB, no
network, no clock), so these cases are fully offline and deterministic. Each case
is labelled by the INTENDED policy (what *should* happen), not by reading the code
back — so a mismatch is a real finding (a bug or a policy gap), not a tautology.
The adversarial `spoof` cases are the point: they assert that lookalike / userinfo
/ subdomain tricks can NEVER mint a trusted tier ("no unverified source enters").

Each case: id, cat, expected (tier, blocked, needs_llm), DocMeta kwargs, why.
Runner: `python -m eval.mimir.evaluate`. Regression guard: tests/test_trust_goldset.py.

Recall the gate order: retracted → blocked-license → DOI(resolves) → arXiv →
active-GitHub → reputable-domain → else web_unknown(+needs_llm). The lone
needs_llm=True is the final fallthrough only; the GitHub-without-release path lands
web_unknown WITHOUT needs_llm.
"""

